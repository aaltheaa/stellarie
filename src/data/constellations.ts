// ── Lookup helpers ────────────────────────────────────────────────────────────

export const CONSTELLATION_MAP = new Map<string, Constellation>(
  CONSTELLATIONS.map(c => [c.id, c])
)

export function getConstellationById(id: string): Constellation | undefined {
  return CONSTELLATION_MAP.get(id)
}

export function getConstellationsByHemisphere(hemisphere: 'north' | 'south'): Constellation[] {
  return CONSTELLATIONS.filter(
    c => c.hemisphere === hemisphere || c.hemisphere === 'both'
  )
}

export function getZodiacConstellations(): Constellation[] {
  return CONSTELLATIONS.filter(c => c.isZodiac).sort((a, b) => a.bestMonth - b.bestMonth)
}

export function getConstellationsByMonth(month: number): Constellation[] {
  // Return constellations best visible within 2 months of the given month
  return CONSTELLATIONS.filter(c => {
    const diff = Math.abs(c.bestMonth - month)
    return diff <= 2 || diff >= 10  // wrap around December/January
  }).sort((a, b) => Math.abs(a.bestMonth - month) - Math.abs(b.bestMonth - month))
}

